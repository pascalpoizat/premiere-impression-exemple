-- F3 : planning de révision (concepts requis d'une candidature)

CREATE TABLE concept_requis (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    candidature_id BIGINT       NOT NULL,
    nom            VARCHAR(120) NOT NULL,
    actuel         INTEGER      NOT NULL,
    requis         INTEGER      NOT NULL,
    qtn            INTEGER      NOT NULL,
    -- ordre d'importance dans l'annonce (à défaut, ordre de saisie) : dernier critère d'égalité du planning
    rang           INTEGER      NOT NULL,
    CONSTRAINT fk_concept_requis_candidature FOREIGN KEY (candidature_id) REFERENCES candidature (id),
    CONSTRAINT uk_concept_requis_nom UNIQUE (candidature_id, nom),
    CONSTRAINT uk_concept_requis_rang UNIQUE (candidature_id, rang),
    CONSTRAINT ck_concept_requis_niveaux CHECK (actuel BETWEEN 0 AND 5 AND requis BETWEEN 0 AND 5),
    CONSTRAINT ck_concept_requis_qtn CHECK (qtn > 0),
    CONSTRAINT ck_concept_requis_rang CHECK (rang >= 1)
);
