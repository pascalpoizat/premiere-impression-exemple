-- F1 : modèle commun de l'équipe (profil, candidature)

CREATE TABLE profil (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pseudo      VARCHAR(50)   NOT NULL,
    competences VARCHAR(5000) NOT NULL,
    CONSTRAINT uk_profil_pseudo UNIQUE (pseudo)
);

CREATE TABLE candidature (
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    profil_id            BIGINT         NOT NULL,
    entreprise           VARCHAR(120)   NOT NULL,
    poste                VARCHAR(120)   NOT NULL,
    texte_annonce        VARCHAR(20000) NOT NULL,
    date_heure_entretien TIMESTAMP,
    adresse_entretien    VARCHAR(255),
    CONSTRAINT fk_candidature_profil FOREIGN KEY (profil_id) REFERENCES profil (id)
);

CREATE INDEX idx_candidature_profil ON candidature (profil_id);
