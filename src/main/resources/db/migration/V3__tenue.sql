-- F2 : ajustement morphologique (mensurations des profils, vêtements et leurs mesures)

CREATE TABLE mensurations (
    profil_id      BIGINT           PRIMARY KEY,
    tour_poitrine  DOUBLE PRECISION NOT NULL,
    tour_taille    DOUBLE PRECISION NOT NULL,
    tour_hanches   DOUBLE PRECISION NOT NULL,
    longueur_jambe DOUBLE PRECISION NOT NULL,
    carrure        DOUBLE PRECISION NOT NULL,
    CONSTRAINT fk_mensurations_profil FOREIGN KEY (profil_id) REFERENCES profil (id),
    CONSTRAINT ck_mensurations_positives CHECK (tour_poitrine > 0 AND tour_taille > 0 AND tour_hanches > 0
        AND longueur_jambe > 0 AND carrure > 0)
);

CREATE TABLE vetement (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    proprietaire_id BIGINT        NOT NULL,
    type            VARCHAR(20)   NOT NULL,
    nom             VARCHAR(120)  NOT NULL,
    description     VARCHAR(1000),
    CONSTRAINT fk_vetement_proprietaire FOREIGN KEY (proprietaire_id) REFERENCES profil (id),
    CONSTRAINT ck_vetement_type CHECK (type IN ('VESTE', 'CHEMISE', 'PANTALON', 'JUPE', 'ROBE'))
);

-- Une ligne par mesure du vêtement : les mesures utiles dépendent de son type
CREATE TABLE mesure_vetement (
    vetement_id BIGINT           NOT NULL,
    mesure      VARCHAR(20)      NOT NULL,
    valeur_cm   DOUBLE PRECISION NOT NULL,
    CONSTRAINT pk_mesure_vetement PRIMARY KEY (vetement_id, mesure),
    CONSTRAINT fk_mesure_vetement FOREIGN KEY (vetement_id) REFERENCES vetement (id) ON DELETE CASCADE,
    CONSTRAINT ck_mesure_nom CHECK (mesure IN ('TOUR_POITRINE', 'TOUR_TAILLE', 'TOUR_HANCHES', 'LONGUEUR_JAMBE', 'CARRURE')),
    CONSTRAINT ck_mesure_valeur CHECK (valeur_cm > 0 AND valeur_cm <= 300)
);

CREATE INDEX idx_vetement_type ON vetement (type);
